class _Row(dict):
    """Mapping row that also preserves sqlite3.Row's integer indexing."""
    def __getitem__(self, key):
        if isinstance(key, int):
            return tuple(self.values())[key]
        return super().__getitem__(key)


class _Cursor:
    def __init__(self, cursor, lastrowid=None):
        self._cursor = cursor
        self.lastrowid = lastrowid

    def _row(self, row):
        if row is None:
            return None
        return _Row(zip((column.name for column in self._cursor.description), row))

    def fetchone(self):
        return self._row(self._cursor.fetchone())

    def fetchall(self):
        return [self._row(row) for row in self._cursor.fetchall()]

    def __iter__(self):
        for row in self._cursor:
            yield self._row(row)


def _postgres_sql(sql: str) -> str:
    ignore_insert = bool(re.search(r"INSERT\s+OR\s+IGNORE\s+INTO", sql, re.I))
    sql = re.sub(r"INSERT\s+OR\s+IGNORE\s+INTO", "INSERT INTO", sql, flags=re.I)
    if ignore_insert:
        sql = sql.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    sql = sql.replace("?", "%s")
    sql = re.sub(r"strftime\('%Y-%m-%dT%H:%M:%fZ','now'\)", "to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD\"T\"HH24:MI:SS.MS\"Z\"')", sql, flags=re.I)
    sql = re.sub(r"strftime\('%Y-%m-%dT%H:%M:%SZ','now','-10 minutes'\)", "to_char((CURRENT_TIMESTAMP AT TIME ZONE 'UTC') - interval '10 minutes','YYYY-MM-DD\"T\"HH24:MI:SS\"Z\"')", sql, flags=re.I)
    sql = re.sub(r"strftime\('%Y-%m-%dT%H:%M:%SZ','now'\)", "to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD\"T\"HH24:MI:SS\"Z\"')", sql, flags=re.I)
    sql = re.sub(r"COLLATE\s+NOCASE", "", sql, flags=re.I)
    sql = re.sub(r"\b(email|username)\s*=\s*%s", r"LOWER(\1)=LOWER(%s)", sql, flags=re.I)
    sql = re.sub(r"\busername\s+LIKE\s+%s", "username ILIKE %s", sql, flags=re.I)
    sql = re.sub(r"INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", sql, flags=re.I)
    sql = re.sub(r"\bMAX\((last_read_message_id|excluded\.last_read_message_id),\s*excluded\.last_read_message_id\)", r"GREATEST(\1, excluded.last_read_message_id)", sql, flags=re.I)
    return sql


class _PostgresConnection:
    def __init__(self, raw):
        self.raw = raw

    def execute(self, sql, parameters=()):
        pragma = re.fullmatch(r"\s*PRAGMA\s+table_info\((\w+)\)\s*", sql, re.I)
        if pragma:
            cursor = self.raw.execute("SELECT column_name AS name, (CASE WHEN is_nullable='NO' THEN 1 ELSE 0 END)::int AS notnull FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=%s ORDER BY ordinal_position", (pragma.group(1),))
            return _Cursor(cursor)
        if re.match(r"\s*PRAGMA\b", sql, re.I):
            return _Cursor(self.raw.execute("SELECT 1 WHERE false"))
        trigger = re.search(r"CREATE\s+TRIGGER\s+IF\s+NOT\s+EXISTS\s+(\w+)\s+AFTER\s+(INSERT|UPDATE)\s+ON\s+(\w+)", sql, re.I)
        if trigger:
            name, event, table = trigger.groups()
            self.raw.execute("""CREATE OR REPLACE FUNCTION studypilot_touch_updated_at() RETURNS trigger
                LANGUAGE plpgsql AS $$ BEGIN
                  IF TG_OP='INSERT' AND NEW.updated_at IS NULL THEN NEW.updated_at := now();
                  ELSIF TG_OP='UPDATE' AND NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN NEW.updated_at := now();
                  END IF; RETURN NEW; END $$""")
            self.raw.execute(f'DROP TRIGGER IF EXISTS "{name}" ON "{table}"')
            return _Cursor(self.raw.execute(f'CREATE TRIGGER "{name}" BEFORE {event} ON "{table}" FOR EACH ROW EXECUTE FUNCTION studypilot_touch_updated_at()'))
        prepared = _postgres_sql(sql)
        wants_id = (bool(re.match(r"\s*INSERT\s+INTO\s+\w+", prepared, re.I))
                    and bool(re.search(r"\bVALUES\s*\(", prepared, re.I))
                    and not re.search(r"\bRETURNING\b", prepared, re.I)
                    and not re.search(r"\bON\s+CONFLICT\b", prepared, re.I))
        if wants_id:
            prepared = prepared.rstrip().rstrip(";") + " RETURNING id"
        self.raw.execute("SAVEPOINT studypilot_statement")
        try:
            cursor = self.raw.execute(prepared, parameters)
            self.raw.execute("RELEASE SAVEPOINT studypilot_statement")
        except Exception as exc:
            self.raw.execute("ROLLBACK TO SAVEPOINT studypilot_statement")
            self.raw.execute("RELEASE SAVEPOINT studypilot_statement")
            try:
                import psycopg
                if isinstance(exc, psycopg.IntegrityError):
                    raise sqlite3.IntegrityError(str(exc)) from exc
            except ImportError:
                pass
            raise
        lastrowid = None
        if wants_id:
            row = cursor.fetchone()
            lastrowid = row[0] if row else None
        return _Cursor(cursor, lastrowid)

    def executemany(self, sql, seq):
        cursor = self.raw.cursor()
        cursor.executemany(_postgres_sql(sql), seq)
        return _Cursor(cursor)


@contextmanager
def connect() -> Iterator[sqlite3.Connection]:
    database_url = os.getenv("DATABASE_URL")
    if database_url:
        import psycopg
        raw = psycopg.connect(database_url, connect_timeout=5, autocommit=False)
        connection = _PostgresConnection(raw)
        try:
            yield connection
            raw.commit()
        except Exception:
            raw.rollback()
            raise
        finally:
            raw.close()
        return
    path = database_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(path, timeout=10)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")
    connection.execute("PRAGMA journal_mode = WAL")
    try:
        with connection:
            yield connection
    finally:
        connection.close()


